#!/usr/bin/env python3
"""
bib2tex.py - write the Publications section of juzb.tex from juzb.bib.

    python3 tools/bib2tex.py juzb.bib juzb.tex          # rewrite the section
    python3 tools/bib2tex.py juzb.bib juzb.tex --dry-run

juzb.bib is the source of truth.  Add or correct an entry there, run this,
rebuild: the .tex section between the generated markers is replaced, and
nothing else in the file is touched.

What it does for each entry, in the order the .bib lists them:

  * renders authors as "F. Surname" - the .bib keeps full given names, and
    only the first initial is printed;
  * sets my own name in bold, found by surname, so no entry has to say so;
  * marks the authors named in \\keepauthors (defined in juzb.tex) with
    \\corr, so the short form never drops them;
  * wraps the authors the short form does drop in \\au / \\auetal, one
    "et al." per entry;
  * links the title, the year and the authors to the DOI, or to the url
    field when the work has no DOI;
  * labels a preprint "medRxiv:<id>", a workshop paper with its booktitle,
    and anything else with its journal.

The year column does the line breaking, so nothing here places one.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

BEGIN = "% >>> publications: generated by tools/bib2tex.py from juzb.bib - do not edit"
END = "% <<< publications"
ME = "Upmeier zu Belzen"
PREPRINTS = {"medrxiv", "biorxiv", "arxiv"}
WIDTH = 96


# ---------------------------------------------------------------- the .bib

def parse_bib(text: str) -> list[dict]:
    """Entries in file order.  Enough BibTeX for a file we write ourselves."""
    out = []
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", text):
        i = text.index("{", m.start())
        depth, j = 0, i
        while j < len(text):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        body = text[i + 1:j]
        entry = {"type": m.group(1).lower(), "key": m.group(2)}
        for f in re.finditer(r"(\w+)\s*=\s*\{", body):
            k = body.index("{", f.start(1) + len(f.group(1)))
            d, e = 0, k
            while e < len(body):
                if body[e] == "{":
                    d += 1
                elif body[e] == "}":
                    d -= 1
                    if d == 0:
                        break
                e += 1
            entry[f.group(1).lower()] = " ".join(body[k + 1:e].split())
        out.append(entry)
    return out


def split_names(field: str) -> list[str]:
    """Split an author field on ' and ', keeping braced surnames whole."""
    parts, buf, depth = [], "", 0
    for tok in re.split(r"(\{|\})", field):
        if tok == "{":
            depth += 1
        elif tok == "}":
            depth -= 1
        if depth == 0 and tok not in "{}":
            chunks = re.split(r"\s+and\s+", tok)
            buf += chunks[0]
            for c in chunks[1:]:
                parts.append(buf)
                buf = c
        else:
            buf += tok
    if buf.strip():
        parts.append(buf)
    return [p.strip() for p in parts if p.strip()]


def render_name(name: str) -> tuple[str, str]:
    """'Family, Given' -> ('F. Family', 'Family'), first initial only."""
    if "," in name:
        family, given = (s.strip() for s in name.split(",", 1))
    else:                                   # 'Given Family', last word is the family
        bits = name.split()
        family, given = bits[-1], " ".join(bits[:-1])
    family = delatex(re.sub(r"^\{(.*)\}$", r"\1", family).strip())
    first = given.split()[0] if given.split() else ""
    first = re.sub(r"^\{(.*)\}$", r"\1", first)
    initial = (first[:2] if first.startswith("\\") else first[:1])
    if first.startswith("{\\"):             # an accented initial, e.g. {\"O}laf
        initial = re.match(r"\{\\.\w?\}?|\{\\.\{?\w\}?\}", first).group(0)
    return (f"{initial}. {family}" if initial else family), family


# ------------------------------------------------------------ the entries

ACCENTS = {'"': "¨", "'": "´", "`": "`", "^": "ˆ", "~": "˜", "c": "¸", "v": "ˇ"}
COMBINE = {'"': "\u0308", "'": "\u0301", "`": "\u0300", "^": "\u0302",
           "~": "\u0303", "c": "\u0327", "v": "\u030c"}


def delatex(text: str) -> str:
    """LaTeX accent escapes -> literal UTF-8.

    The .bib keeps the escapes, because that is what every BibTeX tool
    writes and reads; the .tex gets the real character, because that is how
    the rest of the document spells names and what tex2html.py can read.
    """
    import unicodedata

    def one(m):
        acc, letter = m.group(1), m.group(2)
        if acc not in COMBINE:
            return m.group(0)
        return unicodedata.normalize("NFC", letter + COMBINE[acc])

    text = re.sub(r"\{\\(.)\s*\{?(\w)\}?\}", one, text)   # {\"u}
    text = re.sub(r"\\(.)\{(\w)\}", one, text)              # \"{u}
    text = re.sub(r"\\([\"\'`^~])(\w)", one, text)           # \"u
    text = text.replace("{\\ss}", "ß").replace("\\ss ", "ß")
    return text


def label(e: dict) -> str:
    """The italic venue that follows the authors."""
    journal = e.get("journal", "")
    if journal.lower() in PREPRINTS and e.get("doi"):
        return "%s:%s" % (journal, e["doi"].split("/", 1)[1])
    return e.get("booktitle") or journal


def link(e: dict) -> str:
    return "https://doi.org/" + e["doi"] if e.get("doi") else e.get("url", "")


def keep_authors(tex: str) -> list[str]:
    """The \\keepauthors list in the .tex: authors the short form never drops."""
    m = re.search(r"\\newcommand\{\\keepauthors\}\{(.*?)\}\s*$", tex, re.M | re.S)
    if not m:
        return []
    body = re.sub(r"%.*", "", m.group(1))          # the macro's line-continuations
    return [n.strip() for n in body.split(",") if n.strip()]


FOLD = {"ü": "ue", "ö": "oe", "ä": "ae", "ß": "ss", "é": "e", "è": "e", "á": "a"}


def key_of(rendered: str) -> tuple[str, str]:
    """('f', 'surname') - what two spellings of one person have in common.

    Umlauts fold the German way, so B{\\"u}rgel in the .bib, Bürgel in
    \\keepauthors and Buergel as another journal spelled it are one person.
    """
    plain = re.sub(r"\\textbf\{(.*)\}", r"\1", rendered)
    plain = re.sub(r"\{\\(.)\{?(\w)\}?\}", r"\2\1", plain)      # {\"u} -> u"
    plain = plain.replace('u"', "ue").replace('o"', "oe").replace('a"', "ae")
    for a, b in FOLD.items():
        plain = plain.replace(a, b)
    plain = re.sub(r"[^A-Za-z. ]", "", plain)
    bits = plain.replace(".", " ").split()
    return (bits[0].lower(), "".join(bits[1:]).lower()) if bits else ("", "")


def authors_block(e: dict, keep_list: list[str]) -> list[str]:
    names, families = zip(*(render_name(n) for n in split_names(e["author"])))
    names = list(names)
    me = next((i for i, f in enumerate(families) if ME in f), None)
    if me is not None:
        names[me] = "\\textbf{%s}" % names[me]

    # \keepauthors protects the BACK of the list only: walk in from the last
    # author while the names are listed, and stop at the first that is not.
    # A listed person who is a middle author on this paper - several moved
    # from middle to last over the years - is not protected here, which also
    # means the omitted authors always form a single run.
    wanted = {key_of(n) for n in keep_list}
    corr = set()
    for i in range(len(names) - 1, -1, -1):
        if key_of(names[i]) not in wanted:
            break
        corr.add(i)
    if not corr:
        corr = {len(names) - 1}
    keep = corr | ({i for i in range(len(names)) if i <= me + 1} if me is not None
                   else set(range(len(names))))

    n = len(names)
    runs, k = {}, 0
    while k < n:
        if k in keep:
            k += 1
            continue
        m = k
        while m < n and m not in keep:
            m += 1
        runs[k] = (m == n)
        k = m
    first = min(runs) if runs else None

    units, k = [], 0
    while k < n:
        if k in runs:
            m = k
            while m < n and m not in keep:
                m += 1
            body = ", ".join(names[k:m]) + ("" if m == n else ", ")
            macro = ("auetalend" if runs[k] else "auetal") if k == first else "au"
            units.append("\\%s{%s}" % (macro, body))
            k = m
        else:
            a = "\\corr{%s}" % names[k] if k in corr else names[k]
            units.append(a + ("." if k == n - 1 else ", "))
            k += 1
    return units


def render(e: dict, keep_list: list[str]) -> list[str]:
    url = link(e)
    title = delatex(e["title"].rstrip())
    if title[-1] not in ".?!":
        title += "."
    out = ["\\yr{\\href{%s}{%s}}\\href{%s}{\\nobold{%s}}\\\\" % (url, e["year"], url, title)]
    line = ""
    for u in authors_block(e, keep_list):
        if line and len(line) + len(u) > WIDTH:
            out.append("\\href{%s}{%s}" % (url, line))
            line = u
        else:
            line += u
    if line:
        out.append("\\href{%s}{%s}" % (url, line))
    lab = delatex(label(e))
    if lab:
        out.append("\\href{%s}{\\textit{%s}}" % (url, lab))
    out.append("\\vspace{3pt}")
    out.append("")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("bib", nargs="?", default="juzb.bib")
    ap.add_argument("tex", nargs="?", default="juzb.tex")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    bib, tex = Path(args.bib), Path(args.tex)
    entries = parse_bib(bib.read_text(encoding="utf-8"))
    src = tex.read_text(encoding="utf-8")
    keep_list = keep_authors(src)
    if not keep_list:
        print("bib2tex: no \\keepauthors in the .tex - only last authors are kept",
              file=sys.stderr)

    block = [BEGIN, ""]
    for e in entries:
        block += render(e, keep_list)
    block.append(END)

    if BEGIN in src and END in src:
        head = src[:src.index(BEGIN)]
        tail = src[src.index(END) + len(END):]
    else:                                   # first run: replace the whole section
        m = re.search(r"^\\section\{Publications\}\s*$", src, re.M)
        if not m:
            sys.exit("bib2tex: no \\section{Publications} and no generated block")
        head = src[:m.end()] + "\n\n"
        # Publications is the last section, so stop at \end{document} when no
        # further \section follows - otherwise the end of the file is eaten
        nxt = re.search(r"^\\section\{|^\\end\{document\}", src[m.end():], re.M)
        if not nxt:
            sys.exit("bib2tex: cannot find where the Publications section ends")
        tail = src[m.end() + nxt.start():]
    # the end marker is a comment, so it must own its line: without the
    # newline it swallows whatever the tail begins with. Strip the blank lines
    # the tail already starts with, or every run leaves one more behind.
    out = head + "\n".join(block) + "\n\n" + tail.lstrip("\n")

    print(f"   {len(entries)} entries, {len(keep_list)} never-hidden author(s)")
    if args.dry_run:
        print("   (dry run, nothing written)")
        return 0
    tex.write_text(out, encoding="utf-8")
    print(f"   wrote the Publications section of {tex}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
